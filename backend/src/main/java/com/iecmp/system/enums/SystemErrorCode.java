package com.iecmp.system.enums;

import lombok.Getter;

/**
 * 一 · 用户与权限 业务错误码（接口文档 16.1 节）。
 *
 * <p>号段：{@code 10001 ~ 20000}。
 * 抛出方式：{@code throw new BusinessException(SystemErrorCode.XXX.getCode(), SystemErrorCode.XXX.getMsg())}；
 * 或使用 {@code Result.fail(code, msg)}。
 *
 * <p><b>常量命名</b>：统一为 {@code E<错误码>}，保证与接口文档一一对应且不重名；
 * 实现时如需更易读的常量名，可重命名并使用 IDE 重构，数值不可变更。
 *
 * @author IECMP 后端组
 */
@Getter
public enum SystemErrorCode {

    /** 账号不存在 */
    E10001(10001, "账号不存在"),

    /** 账号被禁用 */
    E10002(10002, "账号被禁用"),

    /** 用户名或密码错误 */
    E10003(10003, "用户名或密码错误"),

    /** 验证码错误或已过期 */
    E10004(10004, "验证码错误或已过期"),

    /** 账号已锁定，请稍后再试 */
    E10005(10005, "账号已锁定，请稍后再试"),

    /** 该账号无前台登录权限 */
    E10006(10006, "该账号无前台登录权限"),

    /** 刷新令牌无效或已过期 */
    E10007(10007, "刷新令牌无效或已过期"),

    /** 手机号已被占用 */
    E10008(10008, "手机号已被占用"),

    /** 邮箱已被占用 */
    E10009(10009, "邮箱已被占用"),

    /** 原密码错误 */
    E10010(10010, "原密码错误"),

    /** 两次输入的新密码不一致 */
    E10011(10011, "两次输入的新密码不一致"),

    /** 用户不存在 */
    E10012(10012, "用户不存在"),

    /** 登录账号已存在 */
    E10013(10013, "登录账号已存在"),

    /** 学号已存在 */
    E10014(10014, "学号已存在"),

    /** 角色不存在 */
    E10015(10015, "角色不存在"),

    /** 不允许禁用超级管理员 */
    E10016(10016, "不允许禁用超级管理员"),

    /** 该用户存在未归还资产 */
    E10017(10017, "该用户存在未归还资产"),

    /** 该用户存在待处理的申请 */
    E10018(10018, "该用户存在待处理的申请"),

    /** 不允许删除超级管理员 */
    E10019(10019, "不允许删除超级管理员"),

    /** 角色名称已存在 */
    E10020(10020, "角色名称已存在"),

    /** 角色编码已存在 */
    E10021(10021, "角色编码已存在"),

    /** 权限码不存在 */
    E10022(10022, "权限码不存在"),

    /** 内置角色不允许修改编码 */
    E10024(10024, "内置角色不允许修改编码"),

    /** 该角色下存在用户，无法删除 */
    E10025(10025, "该角色下存在用户，无法删除"),

    /** 内置角色不允许删除 */
    E10026(10026, "内置角色不允许删除"),

    /** 不允许修改超级管理员的权限 */
    E10027(10027, "不允许修改超级管理员的权限"),

    /** 邀请码无效或已失效 */
    E10028(10028, "邀请码无效或已失效"),

    /** 邀请码使用次数已达上限 */
    E10029(10029, "邀请码使用次数已达上限"),

    /** 提交过于频繁，请稍后再试 */
    E10030(10030, "提交过于频繁，请稍后再试"),

    /** 注册申请不存在 */
    E10031(10031, "注册申请不存在"),

    /** 该注册申请已处理 */
    E10032(10032, "该注册申请已处理"),

    /** 邀请码不存在 */
    E10033(10033, "邀请码不存在"),

    /** 该学号已存在账号，无法重复申请 */
    E10034(10034, "该学号已存在账号，无法重复申请");

    private final Integer code;
    private final String msg;

    SystemErrorCode(Integer code, String msg) {
        this.code = code;
        this.msg = msg;
    }

    /** 按错误码反查，查不到返回 null。 */
    public static SystemErrorCode of(Integer code) {
        if (code != null) {
            for (SystemErrorCode item : values()) {
                if (item.code.equals(code)) {
                    return item;
                }
            }
        }
        return null;
    }

    /** 取错误文案，查不到返回兜底文案。 */
    public static String msgOf(Integer code) {
        SystemErrorCode item = of(code);
        return item == null ? "未知业务错误" : item.msg;
    }
}
